using System;
using System.Collections.Generic;
using System.Linq;
using MFilesAPI;
using MFEventHandler = MFilesAPI.EventHandler;

namespace MFilesMCP.VaultApp
{
	/// <summary>
	/// The vault's VBScript event handlers (M-Files Admin → Event Handlers),
	/// including VaultExtensionMethod handlers. M-Files only saves the whole
	/// list at once, so every change re-reads the list, refuses if it differs
	/// from what the caller last saw, and checks afterwards that every other
	/// handler is unchanged. Handlers are never deleted; switch one off with
	/// active=false. Admin session only.
	/// </summary>
	internal static class EventHandlerChanges
	{
		private sealed class Snapshot
		{
			public string Guid;
			public MFEventHandlerType Type;
			public string Name;
			public bool Active;
			public string Script;

			public static Snapshot Of(MFEventHandler h)
			{
				return new Snapshot { Guid = Normalize(h.GUID), Type = h.EventType, Name = h.Description ?? "", Active = h.Active, Script = h.VBScript ?? "" };
			}

			public bool SameAs(Snapshot other)
			{
				return other.Type == Type && other.Name == Name && other.Active == Active && other.Script == Script;
			}
		}

		public static object Read(JobContext context)
		{
			var handlers = context.Admin().ManagementOperations.GetEventHandlers();
			var views = new List<object>();
			var position = 0;
			foreach (MFEventHandler h in handlers)
				views.Add(Views.Handler(h, ++position));
			return new { count = views.Count, handlers = views };
		}

		public static object Set(JobContext context, SetEventHandlerRequest request)
		{
			var vault = context.Admin();
			context.Step("reading event handlers");
			var handlers = vault.ManagementOperations.GetEventHandlers();
			var before = Snapshots(handlers);
			var expected = new HashSet<string>((request.ExpectedGuids ?? new List<string>()).Select(Normalize));
			var current = new HashSet<string>(before.Select(h => h.Guid));
			if (!current.SetEquals(expected))
				throw new InvalidOperationException(
					$"The vault's event handlers changed since they were read ({before.Count} now, {expected.Count} expected). Read them again and retry. Nothing was changed.");

			MFEventHandler target = null;
			object previous = null;
			var targetGuid = string.IsNullOrWhiteSpace(request.Guid) ? null : Normalize(request.Guid);
			if (targetGuid != null)
			{
				var position = 0;
				foreach (MFEventHandler h in handlers)
				{
					position++;
					if (Normalize(h.GUID) == targetGuid)
					{
						target = h;
						previous = Views.Handler(h, position);
						break;
					}
				}
				if (target == null)
					throw new ArgumentException($"There's no event handler with GUID {request.Guid}.");
				var app = Views.GeneratedBy(target.VBScript);
				if (app != null)
					throw new ArgumentException(
						$"Event handler {request.Guid} was generated by vault application {app} and is managed by M-Files; change the application instead.");
				if (request.EventType != null)
					target.EventType = Util.ParseEnum<MFEventHandlerType>(request.EventType, "MFEventHandler", "event_type");
				if (request.Name != null)
					target.Description = request.Name;
				if (request.Script != null)
					target.VBScript = request.Script;
				if (request.Active.HasValue)
					target.Active = request.Active.Value;
			}
			else
			{
				target = new MFEventHandler();
				target.EventType = Util.ParseEnum<MFEventHandlerType>(request.EventType, "MFEventHandler", "event_type");
				target.Description = request.Name ?? "";
				target.VBScript = Util.RequireText(request.Script, "script");
				target.Active = request.Active ?? true;
				if (target.EventType == MFEventHandlerType.MFEventHandlerVaultExtensionMethod
					|| target.EventType == MFEventHandlerType.MFEventHandlerVaultAnonymousExtensionMethod)
				{
					var methodName = Util.RequireText(request.Name, "name (the extension method's name)");
					if (before.Any(h => h.Type == target.EventType && string.Equals(h.Name, methodName, StringComparison.OrdinalIgnoreCase)))
						throw new ArgumentException($"There's already a {Views.EventTypeName(target.EventType)} handler named \"{methodName}\".");
				}
				handlers.Add(-1, target);
			}
			var wanted = Snapshot.Of(target);

			context.Step("saving event handlers");
			vault.ManagementOperations.SetEventHandlers(handlers);

			context.Step("checking the saved event handlers");
			var savedList = vault.ManagementOperations.GetEventHandlers();
			var after = Snapshots(savedList);
			var problems = new List<string>();
			foreach (var old in before.Where(h => h.Guid != targetGuid))
			{
				var now = after.FirstOrDefault(h => h.Guid == old.Guid);
				if (now == null)
					problems.Add($"handler {old.Guid} ({old.Name}) is gone");
				else if (!now.SameAs(old))
					problems.Add($"handler {old.Guid} ({old.Name}) changed");
			}
			Snapshot saved;
			if (targetGuid != null)
			{
				saved = after.FirstOrDefault(h => h.Guid == targetGuid);
			}
			else
			{
				var added = after.Where(h => !current.Contains(h.Guid)).ToList();
				saved = added.Count == 1 ? added[0] : null;
				if (added.Count != 1)
					problems.Add($"{added.Count} new handlers instead of 1");
			}
			if (saved == null)
				problems.Add("the changed handler isn't in the saved list");
			else if (!saved.SameAs(wanted))
				problems.Add("the changed handler didn't save as sent");
			if (problems.Count > 0)
				throw new InvalidOperationException($"The event handlers were saved but {string.Join("; ", problems)}.");

			object view = null;
			var index = 0;
			foreach (MFEventHandler h in savedList)
			{
				index++;
				if (saved != null && Normalize(h.GUID) == saved.Guid)
					view = Views.Handler(h, index);
			}
			return new { created = targetGuid == null, handler = view, previous, count = after.Count };
		}

		private static List<Snapshot> Snapshots(EventHandlers handlers)
		{
			var list = new List<Snapshot>();
			foreach (MFEventHandler h in handlers)
				list.Add(Snapshot.Of(h));
			return list;
		}

		private static string Normalize(string guid)
		{
			return (guid ?? "").Trim().Trim('{', '}').ToUpperInvariant();
		}
	}
}
